class RealLanDaemonProcess:
    """
    Spawns and manages the compiled airctrl-lan daemon process.
    Binds to an isolated free port, verifies /health endpoint, and
    ensures clean termination on teardown.
    """
    def __init__(self, port: Optional[int] = None, artifact_path: Optional[str] = None):
        self.repo_root = REPO_ROOT
        self.binary_path = os.path.join(self.repo_root, "target", "debug", "airctrl-lan")
        self.port = port or find_free_port()
        self.artifact_path = artifact_path or os.path.join(self.repo_root, "dist", "airctrl.exe")
        self.process: Optional[subprocess.Popen] = None
        self.base_url: Optional[str] = None
        self.host = "127.0.0.1"

    def start(self, timeout: float = 6.0) -> Tuple[str, int]:
        # Compile binary if not present
        if not os.path.exists(self.binary_path):
            compile_res = subprocess.run(
                ["cargo", "build", "--bin", "airctrl-lan"],
                cwd=self.repo_root,
                capture_output=True,
                text=True
            )
            if compile_res.returncode != 0:
                raise RuntimeError(f"cargo build --bin airctrl-lan failed:\n{compile_res.stderr}")

        env = os.environ.copy()
        env["AIRCTRL_PORT"] = str(self.port)
        env["AIRCTRL_ARTIFACT_PATH"] = self.artifact_path

        cmd = [
            self.binary_path,
            "--port", str(self.port),
            "--artifact", self.artifact_path
        ]

        self.process = subprocess.Popen(
            cmd,
            cwd=self.repo_root,
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True
        )

        self.base_url = f"http://{self.host}:{self.port}"

        # Poll /health endpoint until online
        start_time = time.perf_counter()
        ready = False
        last_err = None

        while time.perf_counter() - start_time < timeout:
            if self.process.poll() is not None:
                _, err = self.process.communicate()
                raise RuntimeError(f"airctrl-lan crashed on startup (code {self.process.returncode}):\n{err}")

            try:
                req = urllib.request.Request(f"{self.base_url}/health")
                with urllib.request.urlopen(req, timeout=0.3) as resp:
                    if resp.status == 200:
                        ready = True
                        break
            except Exception as e:
                last_err = e
                time.sleep(0.04)

        if not ready:
            self.stop()
            raise TimeoutError(f"airctrl-lan failed to respond on {self.base_url} within {timeout}s: {last_err}")

        return self.host, self.port

    def stop(self):
        if self.process and self.process.poll() is None:
            self.process.terminate()
            try:
                self.process.wait(timeout=2.0)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait(timeout=1.0)
        self.process = None

    def __enter__(self):
        self.start()
        return self

    def __exit__(self, exc_type, exc_val, exc_tb):
        self.stop()


class PeArtifactInspector:
    """
    Parses and validates PE32+ 64-bit Windows executables (dist/airctrl.exe)
    using Python standard library struct and hashlib.
    """
    @staticmethod
    def inspect(file_path: Optional[str] = None) -> Dict[str, Any]:
        target_path = file_path or os.path.join(REPO_ROOT, "dist", "airctrl.exe")
        if not os.path.exists(target_path):
            raise FileNotFoundError(f"Binary artifact not found: {target_path}")

        file_size = os.path.getsize(target_path)
        with open(target_path, "rb") as f:
            data = f.read()

        if len(data) < 64:
            raise ValueError("File is smaller than minimal DOS header")

        dos_magic = data[:2]
        if dos_magic != b"MZ":
            raise ValueError(f"Invalid DOS magic: {dos_magic} (expected b'MZ')")

        e_lfanew = struct.unpack_from("<I", data, 0x3C)[0]
        if e_lfanew + 24 > len(data):
            raise ValueError(f"e_lfanew offset {e_lfanew} out of file range")

        pe_sig = data[e_lfanew:e_lfanew+4]
        if pe_sig != b"PE\x00\x00":
            raise ValueError(f"Invalid PE signature: {pe_sig}")

        coff_offset = e_lfanew + 4
        machine, num_sections, _, _, _, opt_hdr_size, characteristics = struct.unpack_from(
            "<HHIIIHH", data, coff_offset
        )

        opt_offset = coff_offset + 20
        opt_magic = struct.unpack_from("<H", data, opt_offset)[0]
        subsystem = struct.unpack_from("<H", data, opt_offset + 68)[0]
        entry_point = struct.unpack_from("<I", data, opt_offset + 16)[0]

        sha256_hash = hashlib.sha256(data).hexdigest()

        # Check .sha256 file if present
        sha_file = target_path + ".sha256"
        expected_sha = None
        if os.path.exists(sha_file):
            with open(sha_file, "r") as sf:
                expected_sha = sf.read().split()[0].strip()

        return {
            "path": target_path,
            "file_size": file_size,
            "dos_magic": dos_magic.decode("latin1"),
            "e_lfanew": e_lfanew,
            "machine": machine,
            "is_x86_64": machine == 0x8664,
            "num_sections": num_sections,
            "characteristics": characteristics,
            "is_executable": bool(characteristics & 0x0002),
            "opt_magic": opt_magic,
            "is_pe32_plus": opt_magic == 0x020B,
            "subsystem": subsystem,
            "is_gui": subsystem == 2,
            "entry_point": entry_point,
            "sha256": sha256_hash,
            "expected_sha256": expected_sha,
            "sha_matches": expected_sha == sha256_hash if expected_sha else True
        }


class PowerShellValidator:
    """
    Validates syntax and injection security of generated run.ps1 scripts.
    Uses 'pwsh' if available, otherwise executes strict lexical AST checks.
    """
    @staticmethod
    def validate(script_text: str) -> Dict[str, Any]:
        results = {
            "valid": True,
            "engine": "ast_lexical",
            "errors": [],
            "cmdlets_found": [],
            "balanced_brackets": True,
            "injection_safe": True
        }

        # Check if pwsh is available
        pwsh_bin = shutil.which("pwsh")
        if pwsh_bin:
            proc = subprocess.run(
                [
                    pwsh_bin, "-NoProfile", "-NonInteractive", "-Command",
                    f"$s = @'\n{script_text}\n'@; [Management.Automation.Language.Parser]::ParseInput($s, [ref]$null, [ref]$errors); if ($errors.Count -gt 0) {{ $errors | ForEach-Object {{ Write-Error $_ }}; exit 1 }}"
                ],
                capture_output=True,
                text=True
            )
            if proc.returncode == 0:
                results["engine"] = "pwsh_system"
                results["valid"] = True
                return results
            else:
                results["errors"].append(proc.stderr.strip())

        # Strict Lexical Bracket & Quote Balancing
        stack = []
        pairs = {')': '(', ']': '[', '}': '{'}
        in_sq = False
        in_dq = False
        escaped = False

        for char in script_text:
            if escaped:
                escaped = False
                continue
            if char == '`':
                escaped = True
                continue
            if char == "'" and not in_dq:
                in_sq = not in_sq
                continue
            if char == '"' and not in_sq:
                in_dq = not in_dq
                continue
            if not in_sq and not in_dq:
                if char in '({[':
                    stack.append(char)
                elif char in ')}]':
                    if not stack or stack[-1] != pairs[char]:
                        results["valid"] = False
                        results["balanced_brackets"] = False
                        results["errors"].append(f"Mismatched bracket: {char}")
                    else:
                        stack.pop()

        if in_sq or in_dq:
            results["valid"] = False
            results["errors"].append("Unterminated string literal")
        if stack:
            results["valid"] = False
            results["balanced_brackets"] = False
            results["errors"].append(f"Unclosed brackets: {stack}")

        # Check for un-substituted template markers
        if "{{HOST_IP}}" in script_text or "{{PORT}}" in script_text:
            results["valid"] = False
            results["errors"].append("Unsubstituted template tokens detected")

        # Cmdlet presence
        for cmd in ["Invoke-RestMethod", "Invoke-WebRequest", "Get-Process", "Stop-Process", "Start-Process", "Get-FileHash"]:
            if re.search(rf"\b{re.escape(cmd)}\b", script_text, re.IGNORECASE):
                results["cmdlets_found"].append(cmd)

        return results


class WorkspaceCoreInspector:
    """
    Validates Cargo workspace configuration and executes core crate tests.
    """
    @staticmethod
    def inspect_workspace() -> Dict[str, Any]:
        manifest_path = os.path.join(REPO_ROOT, "Cargo.toml")
        with open(manifest_path, "r") as f:
            content = f.read()

        members_match = re.search(r'members\s*=\s*\[(.*?)\]', content, re.DOTALL)
        members = re.findall(r'"([^"]+)"', members_match.group(1)) if members_match else []
        all_exist = all(os.path.isdir(os.path.join(REPO_ROOT, m)) for m in members)
        return {
            "members": members,
            "member_count": len(members),
            "all_exist": all_exist,
            "manifest_path": manifest_path
        }

    @staticmethod
    def run_core_tests() -> subprocess.CompletedProcess:
        return subprocess.run(
            ["cargo", "test", "-p", "airctrl-core"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True
        )



class Landmark3D:
    def __init__(self, x: float, y: float, z: float = 0.0):
        self.x = float(x)
        self.y = float(y)
        self.z = float(z)

    def to_dict(self) -> Dict[str, float]:
        return {"x": self.x, "y": self.y, "z": self.z}


def create_mock_hand_landmarks(gesture: str = "Neutral") -> List[Landmark3D]:
    """
    Generates a 21-landmark array representing a specific hand pose.
    Index 0: Wrist
    Index 4: Thumb Tip
    Index 8: Index Tip
    Index 12: Middle Tip
    Index 16: Ring Tip
    Index 20: Pinky Tip
    """
    landmarks = [Landmark3D(0.5, 0.8, 0.0) for _ in range(21)]
    # Set wrist
    landmarks[0] = Landmark3D(0.5, 0.8, 0.0)
    # Default separated fingertips for neutral pose (distance > 0.10)
    landmarks[4] = Landmark3D(0.35, 0.60, 0.0)  # Thumb tip
    landmarks[8] = Landmark3D(0.48, 0.50, 0.0)  # Index tip (dist ~ 0.16 > 0.05)
    landmarks[12] = Landmark3D(0.55, 0.52, 0.0) # Middle tip
    landmarks[16] = Landmark3D(0.62, 0.55, 0.0) # Ring tip
    landmarks[20] = Landmark3D(0.68, 0.60, 0.0) # Pinky tip

    if gesture == "Pinch":
        # Thumb tip (4) and Index tip (8) close together (dist <= 0.05)
        landmarks[4] = Landmark3D(0.51, 0.40, 0.0)
        landmarks[8] = Landmark3D(0.53, 0.41, 0.0)  # dist ~ 0.022
        # Others curled
        landmarks[12] = Landmark3D(0.60, 0.65, 0.0)
        landmarks[16] = Landmark3D(0.65, 0.70, 0.0)
        landmarks[20] = Landmark3D(0.70, 0.75, 0.0)

    elif gesture == "Pointing":
        # Index tip (8) extended upward, thumb and others curled
        landmarks[8] = Landmark3D(0.50, 0.20, 0.0)  # extended
        landmarks[7] = Landmark3D(0.50, 0.35, 0.0)  # DIP
        landmarks[6] = Landmark3D(0.50, 0.50, 0.0)  # PIP
        landmarks[4] = Landmark3D(0.40, 0.60, 0.0)  # thumb curled
        landmarks[12] = Landmark3D(0.55, 0.65, 0.0) # middle curled
        landmarks[16] = Landmark3D(0.60, 0.70, 0.0) # ring curled
        landmarks[20] = Landmark3D(0.65, 0.75, 0.0) # pinky curled

    elif gesture == "OpenPalm":
        # All 5 fingers extended upward
        landmarks[4] = Landmark3D(0.30, 0.40, 0.0)
        landmarks[8] = Landmark3D(0.40, 0.20, 0.0)
        landmarks[12] = Landmark3D(0.50, 0.18, 0.0)
        landmarks[16] = Landmark3D(0.60, 0.22, 0.0)
        landmarks[20] = Landmark3D(0.70, 0.30, 0.0)

    return landmarks


class GestureClassifier:
    """
    Classifies 21 3D landmarks into Pointing, Pinch, OpenPalm, Swipe, or Neutral.
    """
    @staticmethod
    def euclidean_dist(p1: Landmark3D, p2: Landmark3D) -> float:
        dx = p1.x - p2.x
        dy = p1.y - p2.y
        dz = p1.z - p2.z
        return math.sqrt(dx * dx + dy * dy + dz * dz)

    def classify(self, landmarks: List[Landmark3D]) -> str:
        if len(landmarks) < 21:
            return "Neutral"

        # Check Pinch: distance between thumb tip (#4) and index tip (#8) <= 0.05
        pinch_dist = self.euclidean_dist(landmarks[4], landmarks[8])
        if round(pinch_dist, 5) <= 0.05:
            return "Pinch"

        # Check Open Palm: all fingertips (4, 8, 12, 16, 20) extended high (y < 0.45)
        tips_extended = all(landmarks[idx].y < 0.45 for idx in [4, 8, 12, 16, 20])
        if tips_extended:
            return "OpenPalm"

        # Check Pointing: index tip (#8) extended (y < 0.35) while middle (#12) and others are curled (y > 0.55)
        if landmarks[8].y < 0.35 and landmarks[12].y > 0.55 and landmarks[16].y > 0.55:
            return "Pointing"

        return "Neutral"


class SpatialRadialDialMapper:
    """
    Maps fingertip coordinates to polar angle, normalized radius, and 6 sectors.
    """
    def __init__(self, sector_count: int = 6, center: Tuple[float, float] = (0.5, 0.5), deadzone: float = 0.10):
        self.sector_count = sector_count
        self.center_x, self.center_y = center
        self.deadzone = deadzone

    def map_coords(self, x: float, y: float) -> Dict[str, Any]:
        dx = x - self.center_x
        dy = y - self.center_y
        radius = math.sqrt(dx * dx + dy * dy)
        normalized_radius = min(1.0, radius / 0.5)

        # In deadzone
        if normalized_radius < self.deadzone:
            return {
                "in_deadzone": True,
                "angle_rad": 0.0,
                "normalized_radius": round(normalized_radius, 3),
                "active_sector": None
            }

        # Calculate angle [0, 2pi)
        angle = math.atan2(dy, dx)
        if angle < 0:
            angle += 2 * math.pi

        # Sector width
        sector_width = (2 * math.pi) / self.sector_count
        sector_idx = int(angle // sector_width) % self.sector_count

        return {
            "in_deadzone": False,
            "angle_rad": round(angle, 4),
            "normalized_radius": round(normalized_radius, 3),
            "active_sector": sector_idx
        }



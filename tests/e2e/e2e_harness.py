class SemanticActionRouter:
    """
    Parses natural language utterances into structured ActionCommand JSON objects.
    """
    SNAP_DIRECTIONS = {
        "left": "Left",
        "right": "Right",
        "top": "Top",
        "bottom": "Bottom",
        "maximize": "Maximize"
    }

    AGENT_TARGETS = {
        "cursor": "Cursor",
        "claude": "Claude",
        "antigravity": "Antigravity",
        "grokbot": "Grokbot",
        "dots": "Dots",
        "muse": "Muse",
        "viktor": "Viktor",
        "gemini": "Gemini"
    }

    def parse(self, utterance: str) -> Dict[str, Any]:
        u = utterance.strip().lower()
        if not u:
            return {"type": "Unknown", "payload": {"query": ""}}

        # Window Snap
        snap_m = re.match(r"(?:snap|dock)\s+(left|right|top|bottom|maximize)", u)
        if snap_m:
            direction = self.SNAP_DIRECTIONS[snap_m.group(1)]
            return {"type": "WindowSnap", "payload": {"direction": direction}}

        # Window Focus
        focus_m = re.match(r"(?:focus|switch to)\s+(.+)", u)
        if focus_m:
            target_name = focus_m.group(1).strip()
            return {"type": "WindowFocus", "payload": {"window_id": 101, "query": target_name}}

        # Window Close
        if u.startswith("close window") or u.startswith("close current"):
            return {"type": "WindowClose", "payload": {"window_id": 101}}

        # Window Minimize
        if u.startswith("minimize window") or u.startswith("minimize"):
            return {"type": "WindowMinimize", "payload": {"window_id": 101}}

        # Launch App
        launch_m = re.match(r"(?:launch|open)\s+(.+)", u)
        if launch_m:
            app_name = launch_m.group(1).strip()
            return {"type": "LaunchApp", "payload": {"app_name": app_name}}

        # Agent Dispatch
        agent_m = re.match(r"(?:ask\s+)?(cursor|claude|antigravity|grokbot|dots|muse|viktor|gemini)[:\s]+(.+)", utterance.strip(), re.IGNORECASE)
        if agent_m:
            target = self.AGENT_TARGETS[agent_m.group(1).lower()]
            prompt = agent_m.group(2).strip()
            return {"type": "AgentDispatch", "payload": {"target": target, "prompt": prompt}}

        # REA Inspect
        rea_m = re.match(r"(?:rea\s+inspect|inspect)\s+(\d+)", u)
        if rea_m:
            pid = int(rea_m.group(1))
            return {"type": "ReaInspect", "payload": {"target_pid": pid, "binary_path": None}}

        # Radial Dial Toggle
        if "radial dial" in u or "toggle dial" in u:
            return {"type": "RadialDialToggle", "payload": {}}

        return {"type": "Unknown", "payload": {"query": utterance}}



use std::net::{Ipv4Addr, Ipv6Addr};

/// Validates whether a string is a valid RFC 1123 hostname.
/// Allows labels of alphanumeric characters and hyphens, separated by periods.
/// Strictly disallows quotes, backticks, dollar signs, parentheses, semicolons, and whitespace.
fn is_valid_rfc1123_hostname(name: &str) -> bool {
    if name.is_empty() || name.len() > 253 {
        return false;
    }
    for label in name.split('.') {
        if label.is_empty() || label.len() > 63 {
            return false;
        }
        if label.starts_with('-') || label.ends_with('-') {
            return false;
        }
        if !label.chars().all(|c| c.is_ascii_alphanumeric() || c == '-') {
            return false;
        }
    }
    true
}

/// Sanitizes and validates a host IP or hostname for inclusion in PowerShell deployment scripts.
///
/// - Valid IPv4 addresses are returned as dotted-quad strings (e.g. "192.168.1.1").
/// - Valid IPv6 addresses (with or without brackets) are returned wrapped in square brackets (e.g. "[::1]").
/// - Valid RFC 1123 hostnames are returned as-is (e.g. "localhost", "windows-build-vm.internal.corp").
/// - Any string containing shell injection characters (`$`, `(`, `)`, `"`, `'`, `;`, newlines, backticks) is rejected.
pub fn sanitize_host_ip(host_ip: &str) -> Result<String, String> {
    let trimmed = host_ip.trim();
    if trimmed.is_empty() {
        return Err("Host IP or hostname cannot be empty".to_string());
    }

    // 1. Check if already bracketed IPv6: "[::1]"
    if trimmed.starts_with('[') && trimmed.ends_with(']') && trimmed.len() > 2 {
        let inner = &trimmed[1..trimmed.len() - 1];
        if inner.parse::<Ipv6Addr>().is_ok() {
            return Ok(format!("[{}]", inner));
        }
    }

    // 2. Check if valid IPv4 address
    if let Ok(ipv4) = trimmed.parse::<Ipv4Addr>() {
        return Ok(ipv4.to_string());
    }

    // 3. Check if valid unbracketed IPv6 address
    if let Ok(ipv6) = trimmed.parse::<Ipv6Addr>() {
        return Ok(format!("[{}]", ipv6));
    }

    // 4. Check if valid RFC 1123 hostname
    if is_valid_rfc1123_hostname(trimmed) {
        return Ok(trimmed.to_string());
    }

    Err(format!("Invalid host IP or hostname: '{}'", host_ip))
}

/// Generates the dynamic PowerShell deployment script (`run.ps1`)
/// configured for the specified host IP and port.
///
/// Applies strict input sanitization and single-quote literal escaping
/// to prevent PowerShell subexpression `$()` or quote breakout injections.
pub fn generate_run_ps1(host_ip: &str, port: u16) -> String {
    let safe_host = match sanitize_host_ip(host_ip) {
        Ok(sanitized) => sanitized,
        Err(err) => {
            tracing::warn!(
                "Unsafe or invalid host_ip '{}' provided to generate_run_ps1: {}. Falling back to '127.0.0.1'",
                host_ip,
                err
            );
            "127.0.0.1".to_string()
        }
    };

    // Escape any single quotes by doubling them (PowerShell literal string escape)
    let escaped_host = safe_host.replace('\'', "''");

    let template = r#"<#
.SYNOPSIS
    airctrl Zero-Friction LAN Deployment and Runner Script
.DESCRIPTION
    Dynamically generated by airctrl-lan daemon on http://{{HOST_IP}}:{{PORT}}
    Downloads, caches, and launches airctrl.exe on Windows.
#>
$ErrorActionPreference = 'Stop'
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8

$HostIp = '{{HOST_IP}}'
$Port = {{PORT}}
$BinaryName = "airctrl.exe"
$InstallDir = "$env:LOCALAPPDATA\airctrl"
$TargetExe = "$InstallDir\$BinaryName"
$TempExePath = "$InstallDir\airctrl.exe.tmp"
$LogPath = "$InstallDir\launch.log"

$BaseUrl = "http://${HostIp}:${Port}"
$DownloadUrl = "${BaseUrl}/$BinaryName"
$MetaUrl = "${BaseUrl}/version"

function Write-DiagLog {
    param([string]$Message, [string]$Level = "INFO")
    $timestamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
    $formatted = "[$timestamp] [$Level] $Message"
    switch ($Level) {
        "INFO"    { Write-Host "[airctrl] $Message" -ForegroundColor Cyan }
        "SUCCESS" { Write-Host "[airctrl] $Message" -ForegroundColor Green }
        "WARN"    { Write-Host "[airctrl] $Message" -ForegroundColor Yellow }
        "ERROR"   { Write-Host "[airctrl] $Message" -ForegroundColor Red }
        Default   { Write-Host "[airctrl] $Message" }
    }
    try {
        $formatted | Out-File -FilePath $LogPath -Append -Encoding utf8 -ErrorAction SilentlyContinue
    } catch {}
}

try {
    Write-DiagLog "Connecting to LAN distribution server at $BaseUrl..." "INFO"

    # Step 1: Ensure local cache directory exists
    if (-not (Test-Path $InstallDir)) {
        Write-DiagLog "Creating local cache directory: $InstallDir" "INFO"
        New-Item -ItemType Directory -Path $InstallDir -Force | Out-Null
    }

    # Step 2: Fetch remote version and build metadata
    Write-DiagLog "Checking remote version and build metadata from $MetaUrl..." "INFO"
    $versionInfo = $null
    try {
        $versionInfo = Invoke-RestMethod -Uri $MetaUrl -Method Get -TimeoutSec 5 -UseBasicParsing
    } catch {
        Write-DiagLog "Unable to reach LAN daemon at $BaseUrl. Ensure host VM is running and port $Port is accessible." "ERROR"
        throw "Failed to query $MetaUrl : $_"
    }

    $remoteSha256 = if ($versionInfo.artifact_sha256) { $versionInfo.artifact_sha256 } else { "" }
    $artifactAvailable = $versionInfo.artifact_available

    if (-not $artifactAvailable) {
        throw "Remote LAN daemon reported artifact_available=false. Please compile airctrl.exe on the host first."
    }

    # Step 3: Check cache status
    $needsDownload = $true
    if (Test-Path $TargetExe) {
        if ($remoteSha256 -ne "") {
            $localHash = (Get-FileHash -Path $TargetExe -Algorithm SHA256).Hash.ToLower()
            if ($localHash -eq $remoteSha256.ToLower()) {
                Write-DiagLog "Local cached binary is up-to-date (SHA256: $localHash). Skipping download." "SUCCESS"
                $needsDownload = $false
            } else {
                Write-DiagLog "New build detected (Local: $localHash, Remote: $remoteSha256). Updating..." "INFO"
            }
        } else {
            Write-DiagLog "Remote SHA256 not provided; proceeding with update to ensure latest version." "WARN"
        }
    } else {
        Write-DiagLog "No cached binary found at $TargetExe. Downloading first-time build..." "INFO"
    }

    # Step 4: Download build if needed (into .tmp file first for atomic replacement)
    if ($needsDownload) {
        Write-DiagLog "Downloading executable from $DownloadUrl..." "INFO"
        if (Test-Path $TempExePath) {
            Remove-Item -Path $TempExePath -Force -ErrorAction SilentlyContinue
        }

        Invoke-WebRequest -Uri $DownloadUrl -OutFile $TempExePath -UseBasicParsing

        if (-not (Test-Path $TempExePath)) {
            throw "Download finished but temporary file $TempExePath was not found."
        }
        $fileSize = (Get-Item $TempExePath).Length
        if ($fileSize -lt 1024) {
            Remove-Item -Path $TempExePath -Force -ErrorAction SilentlyContinue
            throw "Downloaded file size is suspiciously small ($fileSize bytes). Download may be corrupted."
        }
        Write-DiagLog "Downloaded $([math]::Round($fileSize / 1MB, 2)) MB successfully." "SUCCESS"
    }

    # Step 5: Terminate any running instances of airctrl to release file locks
    $runningProcesses = Get-Process -Name "airctrl" -ErrorAction SilentlyContinue
    if ($runningProcesses) {
        Write-DiagLog "Terminating existing airctrl process(es) to release file locks..." "WARN"
        Stop-Process -Name "airctrl" -Force -ErrorAction SilentlyContinue
        
        $sw = [System.Diagnostics.Stopwatch]::StartNew()
        while ((Get-Process -Name "airctrl" -ErrorAction SilentlyContinue) -and ($sw.Elapsed.TotalSeconds -lt 3)) {
            Start-Sleep -Milliseconds 200
        }
        if (Get-Process -Name "airctrl" -ErrorAction SilentlyContinue) {
            Write-DiagLog "Forcing termination of residual airctrl processes..." "WARN"
            Stop-Process -Name "airctrl" -Force -ErrorAction SilentlyContinue
            Start-Sleep -Milliseconds 300
        }
    }

    # Step 6: Atomic replacement if new build downloaded
    if ($needsDownload -and (Test-Path $TempExePath)) {
        Move-Item -Path $TempExePath -Destination $TargetExe -Force
        Write-DiagLog "Cached binary replaced at: $TargetExe" "SUCCESS"
    }

    # Step 7: Launch airctrl process detached
    Write-DiagLog "Launching airctrl process..." "INFO"
    $proc = Start-Process -FilePath $TargetExe -WorkingDirectory $InstallDir -PassThru
    Write-DiagLog "airctrl launched successfully with PID: $($proc.Id)" "SUCCESS"

} catch {
    Write-DiagLog "Deployment failed: $_" "ERROR"
    Write-DiagLog "Script StackTrace: $($_.ScriptStackTrace)" "ERROR"
    exit 1
}
"#;

    template
        .replace("{{HOST_IP}}", &escaped_host)
        .replace("{{PORT}}", &port.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_generate_run_ps1_interpolates_values() {
        let script = generate_run_ps1("192.168.144.110", 8080);
        assert!(script.contains(r#"$HostIp = '192.168.144.110'"#));
        assert!(script.contains(r#"$Port = 8080"#));
        assert!(!script.contains("{{HOST_IP}}"));
        assert!(!script.contains("{{PORT}}"));
    }

    #[test]
    fn test_sanitize_host_ip_ipv4() {
        assert_eq!(sanitize_host_ip("192.168.1.1").unwrap(), "192.168.1.1");
        assert_eq!(sanitize_host_ip("127.0.0.1").unwrap(), "127.0.0.1");
        assert_eq!(sanitize_host_ip("0.0.0.0").unwrap(), "0.0.0.0");
    }

    #[test]
    fn test_sanitize_host_ip_ipv6_brackets() {
        assert_eq!(sanitize_host_ip("::1").unwrap(), "[::1]");
        assert_eq!(sanitize_host_ip("[::1]").unwrap(), "[::1]");
        assert_eq!(sanitize_host_ip("fe80::1ff:fe00:1").unwrap(), "[fe80::1ff:fe00:1]");
        assert_eq!(sanitize_host_ip("[fe80::1ff:fe00:1]").unwrap(), "[fe80::1ff:fe00:1]");
    }

    #[test]
    fn test_sanitize_host_ip_hostnames() {
        assert_eq!(sanitize_host_ip("localhost").unwrap(), "localhost");
        assert_eq!(sanitize_host_ip("windows-build-vm.internal.corp").unwrap(), "windows-build-vm.internal.corp");
    }

    #[test]
    fn test_sanitize_host_ip_rejects_malicious() {
        assert!(sanitize_host_ip("$(calc.exe)").is_err());
        assert!(sanitize_host_ip("192.168.1.1\" ; evil").is_err());
        assert!(sanitize_host_ip("192.168.1.1\r\nevil").is_err());
        assert!(sanitize_host_ip("192.168.1.1`").is_err());
        assert!(sanitize_host_ip("$env:COMPUTERNAME").is_err());
    }

    #[test]
    fn test_generate_run_ps1_falls_back_safely_on_injection() {
        let evil_script = generate_run_ps1("$(calc.exe)", 8080);
        assert!(evil_script.contains(r#"$HostIp = '127.0.0.1'"#));
        assert!(!evil_script.contains("calc.exe"));
    }
}
